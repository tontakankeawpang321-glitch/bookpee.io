export function extractYouTubeId(url: string): string {
  if (!url) return '';
  const match = url.match(/(?:v=|\/embed\/|youtu\.be\/|\/v\/|\/e\/|watch\?v=)([^&?#/]+)/);
  return match && match[1] ? match[1] : '';
}

export function parseVideosCSV(csv: string): VideoClip[] {
  const lines = csv.trim().split('\n');
  if (lines.length < 2) return [];

  const clips: VideoClip[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Handle quoted values like "Moby Dick หรือ, วาฬ"
    let category = '';
    let title = '';
    let url = '';

    if (line.includes('"')) {
      // Regex parsing for CSV line with quotes
      const match = line.match(/^([^,]+),(".*?"|[^,]+),(https?:\/\/.+)$/);
      if (match) {
        category = match[1].trim();
        title = match[2].replace(/^"|"$/g, '').trim();
        url = match[3].trim();
      }
    } else {
      const parts = line.split(',');
      if (parts.length >= 3) {
        category = parts[0].trim();
        title = parts[1].trim();
        url = parts.slice(2).join(',').trim();
      }
    }

    if (!url || !url.startsWith('http')) continue;

    const youtubeId = extractYouTubeId(url);

    clips.push({
      id: `vid-sheet-${i}`,
      title: title || 'เรื่องเล่าพอตแคสต์',
      category: category || 'โปรเจคกูเทนเบริค',
      url,
      youtubeId: youtubeId || '',
      channelName: category || 'โปรเจคกูเทนเบริค',
      description: `พอตแคสต์เล่าเรื่องวรรณกรรม ${title}`
    });
  }

  return clips;
}

